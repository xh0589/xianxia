function _storyState() {
    var cd = window.currentCharData;
    if (!cd) return null;
    if (!cd._sectStory || typeof cd._sectStory !== 'object') cd._sectStory = {};
    return cd._sectStory;
}

function _save() {
    try { if (window.StateRegistry && typeof window.StateRegistry.saveAll === 'function') window.StateRegistry.saveAll(); } catch (e) {}
}

// 当前该演哪一幕（贡献门槛 + 未演过）；无戏可演返回 null
function getPendingStage(sectName) {
    var ds = window.discipleState;
    if (!ds || !ds.isInSect) return null;
    var arc = SECT_STORY_ARCS[sectName];
    if (!arc) return null;
    var st = _storyState();
    var rec = st[sectName] || { stage: -1 };
    var contrib = Number(ds.contribution) || 0;
    for (var i = rec.stage + 1; i < arc.stages.length; i++) {
        if (contrib >= STAGE_REQ[i]) return i;
    }
    return null;
}

// 演一幕：弹窗 + 选项当场落账
function playSectStory(sectName, stageIdx) {
    var arc = SECT_STORY_ARCS[sectName];
    if (!arc || !arc.stages[stageIdx]) return false;
    var stage = arc.stages[stageIdx];
    if (typeof window.showModal !== 'function') return false; // 无头环境不弹不记，改日再来

    var html = '<p class="text-xs text-amber-400 mb-2">' + arc.name + ' · 第' + (stageIdx + 1) + '折 「' + stage.title + '」</p>';
    for (var i = 0; i < stage.scenes.length; i++) {
        html += '<p class="text-sm text-gray-200 mb-2">' + stage.scenes[i] + '</p>';
    }
    html += '<div style="display:flex;flex-direction:column;gap:8px;margin-top:10px">';
    for (var c = 0; c < stage.choices.length; c++) {
        html += '<button onclick="window._resolveSectStory(\'' + sectName + '\',' + stageIdx + ',' + c + '); this.closest(\'#xianxia-modal-overlay\').remove();" '
            + 'class="bg-amber-800 hover:bg-amber-700 text-amber-100 text-xs px-3 py-2 rounded text-left w-full">' + stage.choices[c].text + '</button>';
    }
    html += '</div>';
    window.showModal('📜 门派故事 · ' + sectName, html);
    return true;
}

// 选项落账：贡献/气运当场给，进度记账
function resolveSectStory(sectName, stageIdx, choiceIdx) {
    var arc = SECT_STORY_ARCS[sectName];
    if (!arc || !arc.stages[stageIdx]) return false;
    var stage = arc.stages[stageIdx];
    var st = _storyState();
    var rec = st[sectName] || { stage: -1, choices: {} };
    if (rec.stage >= stageIdx) return false; // 一幕只演一次
    var choice = stage.choices[choiceIdx] || stage.choices[0];
    var eff = choice.effect || {};
    if (eff.contribution && window.discipleState) {
        window.discipleState.contribution = (Number(window.discipleState.contribution) || 0) + eff.contribution;
    }
    if (eff.luck && window.currentCharData) {
        window.currentCharData.luck = Math.max(0, Math.min(100, (Number(window.currentCharData.luck) || 50) + eff.luck));
    }
    rec.stage = stageIdx;
    rec.choices = rec.choices || {};
    rec.choices[stageIdx] = choiceIdx;
    st[sectName] = rec;
    var parts = [];
    if (eff.contribution) parts.push('门派贡献+' + eff.contribution);
    if (eff.luck > 0) parts.push('气运+' + eff.luck);
    if (eff.luck < 0) parts.push('气运' + eff.luck);
    if (window.showMessage) window.showMessage('📜 ' + choice.result + (parts.length ? '\n（' + parts.join('，') + '）' : ''), 'success');
    if (window.updateCharacterStatus) window.updateCharacterStatus();
    _save();
    return true;
}

// 每日钩子：至多一幕
function checkSectStory() {
    var ds = window.discipleState;
    if (!ds || !ds.isInSect) return false;
    var sectName = ds.sectId || ds.sectName;
    if (!sectName) return false;
    var stage = getPendingStage(sectName);
    if (stage == null) return false;
    return playSectStory(sectName, stage);
}

if (window.timeSystem && typeof window.timeSystem.onNewDaySubscribe === 'function') {
    window.timeSystem.onNewDaySubscribe(checkSectStory);
}

