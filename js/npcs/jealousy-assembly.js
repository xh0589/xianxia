    var LEDGER_KEY = 'xianxia_asm_ledger';
    var _ledger = null;
    function _ldgLoad() {
        if (_ledger) return _ledger;
        _ledger = [];
        try {
            var raw = localStorage.getItem(LEDGER_KEY);
            if (raw) {
                var p = JSON.parse(raw);
                if (Array.isArray(p)) _ledger = p;
            }
        } catch (e) {}
        return _ledger;
    }
    function _ldgSave() {
        try { localStorage.setItem(LEDGER_KEY, JSON.stringify(_ledger.slice(-60))); } catch (e) {}
    }
    window._asmLedgerAdd = function (hostId, guestId, choice) {
        var ld = _ldgLoad();
        var day = (window.timeSystem && window.timeSystem.gameTime && window.timeSystem.gameTime.currentDay) || 1;
        ld.push({ h: hostId, g: guestId, day: day, choice: choice || 'both', after: false });
        _ldgSave();
    };
    window._asmLedgerGet = _ldgLoad;
    // 重读账本（多标签页/调试用）：丢弃内存缓存，从存档重新加载
    window._asmLedgerReload = function () { _ledger = null; return _ldgLoad(); };
    function _ldgPairDay(h, g) {
        // 两人最近一次同框的日子（无则 0）
        var ld = _ldgLoad(), best = 0;
        for (var i = 0; i < ld.length; i++) {
            var e = ld[i];
            if ((e.h === h && e.g === g) || (e.h === g && e.g === h)) best = Math.max(best, e.day || 0);
        }
        return best;
    }
    function _ldgPendingAftermath(today, loc) {
        // 余波待发：照面后 3~10 日内、余波未演、且当事一方的门派就是玩家所在地
        var ld = _ldgLoad();
        for (var i = ld.length - 1; i >= 0; i--) {
            var e = ld[i];
            if (e.after || !e.day) continue;
            var dt = today - e.day;
            if (dt < 3 || dt > 10) continue;
            var hs = _asmSectOf(e.h), gs = _asmSectOf(e.g);
            if (hs === loc) return { entry: e, idx: i, speaker: e.h, other: e.g };
            if (gs === loc) return { entry: e, idx: i, speaker: e.g, other: e.h };
        }
        return null;
    }
    function _asmSectOf(id) {
        var roster = (typeof window._jealRosterAll === 'function') ? window._jealRosterAll() : [];
        for (var i = 0; i < roster.length; i++) if (roster[i].id === id) return roster[i].sect || '';
        if (typeof id === 'string' && id.indexOf('sect_leader_') === 0) return id.slice('sect_leader_'.length);
        return '';
    }

