const BEAST_PREFIXES = ['赤', '青', '金', '银', '铁', '风', '雷', '火', '冰', '玄', '幽', '冥', '星', '月', '毒', '血', '骨', '影', '霜', '炎'];
const BEAST_SUFFIXES = ['狼', '虎', '鹰', '蛇', '蛟', '龟', '猿', '蝎', '蛛', '蟒', '熊', '豹', '狐', '鹤', '龙', '蜥', '蝠', '蜈', '蟾', '蜂'];

// ================================================================
//  4. 工具函数
// ================================================================
function rand(min, max) {
    return Math.floor(Math.random() * (max - min + 1)) + min;
}

function pick(arr) {
    return arr[rand(0, arr.length - 1)];
}

// ================================================================
//  5. 核心生成函数
// ================================================================

/**
 * 生成人类姓名
 * @param {number} [nameCount] 名字字数：1或2（默认80%双名/20%单名）
 * @returns {{ full: string, surname: string, given: string, type: '单名'|'双名' }}
 */
function generateName(nameCount) {
    const surname = pick(SURNAMES);
    let count = nameCount;
    if (count === undefined) count = Math.random() < 0.8 ? 2 : 1;
    count = Math.min(2, Math.max(1, count));
    let given = '';
    if (count === 1) {
        given = pick(GIVEN_NAMES);
    } else {
        let first = pick(GIVEN_NAMES);
        let second = pick(GIVEN_NAMES);
        let tries = 0;
        while (first === second && tries < 20) { second = pick(GIVEN_NAMES); tries++; }
        given = first + second;
    }
    return { full: surname + given, surname, given, type: count === 1 ? '单名' : '双名' };
}

/**
 * 批量生成人类姓名
 * @param {number} n 数量
 * @returns {Array}
 */
function generateBatch(n) {
    const result = [];
    for (let i = 0; i < n; i++) result.push(generateName());
    return result;
}

/**
 * 生成野兽名称
 * @returns {string} 如"赤炎狼"、"幽冥虎"
 */
function generateBeastName() {
    const prefix = pick(BEAST_PREFIXES);
    const suffix = pick(BEAST_SUFFIXES);
    // 30%概率加"兽"字后缀
    if (Math.random() < 0.3) {
        return prefix + suffix + '兽';
    }
    return prefix + suffix;
}

/**
 * 根据职业给姓名加称谓
 * @param {string} name 姓名
 * @param {string} [occupation] 职业
 * @returns {string}
 */
function formatNameWithTitle(name, occupation) {
    if (!occupation) return name;
    const titles = {
        '导师': '先生', '治疗师': '医师', '商人': '掌柜', '长老': '长老',
        '战士': '壮士', '铁匠': '师傅', '炼丹师': '丹师', '隐士': '居士',
        '村民': '老丈', '竞争对手': '道友'
    };
    const title = titles[occupation] || '道友';
    return `${name}${title}`;
}

